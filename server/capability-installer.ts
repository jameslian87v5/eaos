// ─── Staged install: copy with symlink rejection ──────────────

function copyDirSync(src: string, dest: string): void {
  fs.mkdirSync(dest, { recursive: true });
  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    // Reject symlinks — supply-chain boundary must not dereference links
    // that could point outside the source package.
    if (entry.isSymbolicLink()) {
      throw new Error(`Symlink found in plugin package: ${entry.name} — symlinks are not allowed`);
    }
    if (entry.isDirectory()) {
      copyDirSync(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

// ─── Validate staged package using REAL validators ────────────
// Instead of duplicating validation logic, construct a temporary config
// entry pointing at the staging directory and call the same resolveOne()
// used by getAllSkills/getAllHookPlugins. This guarantees identical
// invariants: plugin.name === name, skills path containment, hooks file
// checks, etc.

function detectPackageCategories(stagingDir: string): Array<"skill" | "hook-plugin"> {
  const categories: Array<"skill" | "hook-plugin"> = [];
  // Read manifest for custom paths (mirrors resolveOne logic in skill-config.ts / hook-plugin-config.ts)
  const pluginJsonPath = path.join(stagingDir, ".claude-plugin", "plugin.json");
  let manifest: any = {};
  if (fs.existsSync(pluginJsonPath)) {
    try {
      manifest = JSON.parse(fs.readFileSync(pluginJsonPath, "utf8"));
    } catch {
      // If manifest is unparseable, fall through to default-path detection
    }
  }
  // Check for skills: <plugin.skills or "skills"> is a directory containing */SKILL.md
  const skillsDecl = typeof manifest.skills === "string" ? manifest.skills : "skills";
  const skillsDir = path.resolve(stagingDir, skillsDecl);
  if (skillsDir.startsWith(stagingDir + path.sep) && fs.existsSync(skillsDir) && fs.statSync(skillsDir).isDirectory()) {
    const skillDirs = fs.readdirSync(skillsDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => path.join(skillsDir, d.name));
    if (skillDirs.some((d) => fs.existsSync(path.join(d, "SKILL.md")))) {
      categories.push("skill");
    }
  }
  // Check for hooks: <plugin.hooks or "hooks/hooks.json"> is a file path (NOT a directory)
  const hooksDecl = typeof manifest.hooks === "string" ? manifest.hooks : "hooks/hooks.json";
  const hooksJsonPath = path.resolve(stagingDir, hooksDecl);
  if (hooksJsonPath.startsWith(stagingDir + path.sep) && fs.existsSync(hooksJsonPath) && fs.statSync(hooksJsonPath).isFile()) {
    categories.push("hook-plugin");
  }
  return categories;
}

function validateStagedPackage(
  stagingDir: string,
  name: string,
  categories: Array<"skill" | "hook-plugin">
): { valid: boolean; version: string; warnings: string[]; error?: string } {
  const warnings: string[] = [];
  let version = "";
  const relPath = path.relative(PROJECT_ROOT, stagingDir);

  if (categories.includes("skill")) {
    const cfg: SkillConfigEntry = { name, type: "plugin", enabled: true, path: relPath };
    const resolved = resolveSkill(cfg);
    if (!resolved.valid) {
      return { valid: false, version: resolved.version || "", warnings, error: resolved.error };
    }
    version = resolved.version || version;
  }

  if (categories.includes("hook-plugin")) {
    const cfg: HookPluginConfigEntry = { name, type: "hook-plugin", enabled: true, path: relPath };
    const resolved = resolveHookPlugin(cfg);
    if (!resolved.valid) {
      return { valid: false, version: resolved.version || "", warnings, error: resolved.error };
    }
    version = resolved.version || version;
  }

  return { valid: true, version, warnings };
}

// ─── Public API: importNativePlugin ───────────────────────────

export function importNativePlugin(req: NativePluginImportRequest): PluginImportResult {
  const { path: srcPath, name, registryCategory, enabled = true } = req;

  // 1. Validate name
  if (!VALID_PLUGIN_NAME.test(name)) {
    throw new Error(`Invalid plugin name "${name}": must match ${VALID_PLUGIN_NAME}`);
  }

  // 2. Validate source path is within import root
  const realSrc = validateImportPath(srcPath);

  // 3. Global uniqueness check — always enforced, no force bypass
  if (!checkGlobalNameUnique(name)) {
    throw new Error(
      `resourceId "${name}" already exists (global uniqueness across skill/mcp/hook-plugin). Uninstall the existing one first.`
    );
  }

  // 4. Unified install path: plugins/<name>/
  const targetDir = path.resolve(PLUGINS_ROOT, name);
  const stagingDir = path.resolve(PLUGINS_ROOT, `${name}.staging`);

  fs.mkdirSync(PLUGINS_ROOT, { recursive: true });

  // 5. Reject if already installed (MVP: no force/overwrite)
  if (fs.existsSync(targetDir)) {
    throw new Error(
      `Plugin "${name}" already installed at ${targetDir}. Uninstall first, then import again.`
    );
  }

  // 6. Clean any leftover staging
  if (fs.existsSync(stagingDir)) fs.rmSync(stagingDir, { recursive: true, force: true });

  try {
    // 7. Copy to staging (rejects symlinks)
    copyDirSync(realSrc, stagingDir);

    // 8. Auto-detect categories from package contents (or use explicit override)
    let categories = registryCategory ? [registryCategory] : detectPackageCategories(stagingDir);
    if (categories.length === 0) {
      throw new Error(
        `Plugin "${name}" has no detectable skills or hooks. ` +
        `Specify registryCategory explicitly or ensure the package contains valid content.`
      );
    }
    if (categories.length > 1) {
      throw new Error(
        `Plugin "${name}" contains both skill and hook content. ` +
        `The current capability resource model uses bare resourceId for uniqueness, ` +
        `so dual-registering is not supported yet. ` +
        `Specify registryCategory explicitly to install as a single type.`
      );
    }

    // 9. Validate staged package using REAL validators (resolveOne) for all categories
    const validation = validateStagedPackage(stagingDir, name, categories);
    if (!validation.valid) {
      throw new Error(`Staged package validation failed: ${validation.error}`);
    }

    // 10. Atomic rename staging → target
    fs.renameSync(stagingDir, targetDir);
    let finalized = false;

    try {
      // 11. Register in config(s) — one package can be in both skills.json and hook-plugins.json
      const relPath = `plugins/${name}`;
      for (const cat of categories) {
        if (cat === "skill") {
          upsertSkillConfig(name, relPath, enabled);
        } else {
          upsertHookPluginConfig(name, relPath, enabled);
        }
      }

      // 12. Verify registration via real resolvers
      for (const cat of categories) {
        const registered = cat === "skill"
          ? getAllSkills().find((s) => s.name === name)
          : getAllHookPlugins().find((p) => p.name === name);
        if (!registered) {
          throw new Error(`Plugin "${name}" installed but not found in ${cat} registry — config may be corrupt`);
        }
        if (!registered.valid) {
          throw new Error(`Plugin "${name}" installed but ${cat} registry validation failed: ${registered.error}`);
        }
      }

      // 13. Hub source-identity marker (codex R5a round-4/5/6): when hubSourceId
      // is set, write .hub-source.json INSIDE the installed resource so idempotency
      // is bound to the resource, not to name-only. Uninstall (rmSync targetDir)
      // naturally removes it; a local re-install won't write it → lookupExisting
      // returns null → import collision fails closed. resolveOne ignores extra
      // root dotfiles (only reads .claude-plugin/plugin.json + skills/*/SKILL.md).
      //
      // REQUIRED + atomic (round-5/6): write temp+rename so a partial marker
      // can't be observed. MUST run BEFORE finalized=true so a write failure
      // (throw) leaves finalized=false → finally cleans targetDir + config.
      // version = req.hubVersion (Hub release version, the resync key), NOT
      // validation.version (plugin.json internal — may differ).
      if (req.hubSourceId) {
        const markerPath = path.join(targetDir, ".hub-source.json");
        const tmpPath = `${markerPath}.${process.pid}.tmp`;
        fs.writeFileSync(tmpPath, JSON.stringify({
          hubSourceId: req.hubSourceId,
          namespaceSlug: req.namespaceSlug ?? null,
          version: req.hubVersion ?? null,
          sha: req.commitHash ?? null,
        }) + "\n");
        try {
          fs.renameSync(tmpPath, markerPath); // atomic on same fs
        } catch (err) {
          try { fs.rmSync(tmpPath, { force: true }); } catch {}
          throw err;
        }
      }

      finalized = true; // all required finalization (incl. marker) succeeded
    } finally {
      if (!finalized) {
        // Late failure after rename: clean up targetDir + all config entries
        if (fs.existsSync(targetDir)) {
          fs.rmSync(targetDir, { recursive: true, force: true });
        }
        removeSkillConfig(name);
        removeHookPluginConfig(name);
      }
    }

    console.log(
      `[capability-installer] Imported native plugin "${name}" (types=[${categories.join(", ")}], v${validation.version}) → ${targetDir}`
    );

    return {
      resourceId: name,
      installedPath: targetDir,
      version: validation.version,
      types: categories,
      valid: true,
      warnings: validation.warnings,
    };
  } catch (err) {
    // Cleanup staging on any failure
    if (fs.existsSync(stagingDir)) {
      fs.rmSync(stagingDir, { recursive: true, force: true });
    }
    throw err;
  }
}

// ─── Public API: uninstallNativePlugin ────────────────────────

export function uninstallNativePlugin(req: UninstallRequest): void {
  const { name, force = false } = req;

  if (!VALID_PLUGIN_NAME.test(name)) {
    throw new Error(`Invalid plugin name "${name}": must match ${VALID_PLUGIN_NAME}`);
  }

  // Find the plugin in skill or hook-plugin registry
  const skillEntry = getAllSkills().find((s) => s.name === name);
  const hookEntry = getAllHookPlugins().find((p) => p.name === name);

  if (!skillEntry && !hookEntry) {
    throw new Error(`Plugin "${name}" not found in skill or hook-plugin registry`);
  }

  // Check references (unless force)
  if (!force) {
    // Lazy import to avoid circular dependency at module load time
    const { applicationCapabilitiesService } = require("./application-capabilities.js");
    const { entitlementService } = require("./entitlement.js");
    const referencingApps = applicationCapabilitiesService.listAppsByResourceId(name);
    const entitlementEntries = entitlementService.listEntries(name);
    const refs: string[] = [];
    if (referencingApps.length > 0) {
      refs.push(`application(s): ${referencingApps.join(", ")}`);
    }
    if (entitlementEntries.length > 0) {
      refs.push(`entitlement entries: ${entitlementEntries.length}`);
    }
    if (refs.length > 0) {
      throw new Error(
        `Plugin "${name}" is referenced by ${refs.join("; ")}. Use force=true to remove anyway.`
      );
    }
    // NOTE: agent activation (data/agent-capabilities.json) lookup not yet
    // implemented — there is no service method to list agents by resourceId.
    // This gap is intentional; activation references become stale but harmless
    // (resolveEnabledResourceIds filters out unknown resources at read time).
  }

  // Remove from unified plugins/ directory + clean up all config entries
  const targetDir = path.resolve(PLUGINS_ROOT, name);
  if (fs.existsSync(targetDir)) {
    fs.rmSync(targetDir, { recursive: true, force: true });
  }
  // Also clean up legacy locations (skills/<name>, hooks/<name>) for plugins installed before unification
  const legacySkillDir = path.resolve(SKILLS_ROOT, name);
  if (fs.existsSync(legacySkillDir)) fs.rmSync(legacySkillDir, { recursive: true, force: true });
  const legacyHookDir = path.resolve(HOOKS_ROOT, name);
  if (fs.existsSync(legacyHookDir)) fs.rmSync(legacyHookDir, { recursive: true, force: true });

  if (skillEntry) {
    removeSkillConfig(name);
    console.log(`[capability-installer] Uninstalled skill plugin "${name}"`);
  }
  if (hookEntry) {
    removeHookPluginConfig(name);
    console.log(`[capability-installer] Uninstalled hook plugin "${name}"`);
  }
}

// ─── Public API: listInstalledPlugins ─────────────────────────

export function listInstalledPlugins(filter?: {
  type?: "skill" | "hook-plugin";
}): InstalledPluginInfo[] {
  const result: InstalledPluginInfo[] = [];

  if (!filter || filter.type === "skill") {
    for (const s of getAllSkills()) {
      result.push({
        name: s.name,
        type: "skill",
        version: s.version,
        description: s.description,
        enabled: s.enabled,
        valid: s.valid,
        path: s.path,
        error: s.error,
        submittedBy: s.submittedBy,
        submissionId: s.submissionId,
      });
    }
  }

  if (!filter || filter.type === "hook-plugin") {
    for (const p of getAllHookPlugins()) {
      result.push({
        name: p.name,
        type: "hook-plugin",
        version: p.version,
        description: p.description,
        enabled: p.enabled,
        valid: p.valid,
        path: p.path,
        error: p.error,
      });
    }
  }

  return result;
}
