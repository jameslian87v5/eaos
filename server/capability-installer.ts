/**
 * capability-installer.ts — Phase 6 (A3 + plugin import)
 *
 * Two install paths:
 * 1. installApiAsMcp() — HTTP API → stdio-wrapper MCP package (A3).
 * 2. importNativePlugin() — SDK native plugin package → skill/hook-plugin (new).
 *
 * Native plugin import security (Codex review evt_20260630_plugin_installer_design):
 *   - Source path realpath must be within PLUGIN_IMPORT_ROOT (default data/skill-hub-cache).
 *   - resourceId (name) is globally unique across skill/mcp/hook-plugin.
 *   - Staged install: copy to <name>.staging → validate → atomic rename.
 *   - No force/overwrite in MVP — uninstall first, then re-import.
 *   - Late failure after rename: targetDir + config entry are cleaned up.
 *   - Config files use write-temp-and-rename.
 *   - Audit records include source metadata but never package payload.
 *
 * MCP wrapper security (Codex A3 review requirement #4):
 *   - API metadata is embedded as a JSON constant inside server.cjs,
 *     NOT string-interpolated into JavaScript fragments.
 *   - The wrapper template is fixed code; only the JSON config object
 *     changes per API. Admin input can never become shell/JS syntax.
 *   - Files are written only under mcp/<name>/ (path containment).
 *   - run.sh is made executable after writing.
 *
 * Idempotency (Codex A3 review requirement #2):
 *   - data/mcp.json updates use write-temp-and-rename to avoid corruption.
 */

