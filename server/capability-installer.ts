// ─── Wrapper template ─────────────────────────────────────────
//
// The template is a fixed JS string. The ONLY variable part is a JSON
// config object embedded at the top. Admin input never becomes JS syntax.

const WRAPPER_TEMPLATE = `#!/usr/bin/env node
// AUTO-GENERATED by capability-installer.ts — DO NOT EDIT.
// stdio MCP wrapper for internal HTTP API.
// The config below is embedded as JSON (never string-interpolated JS).

const CONFIG = __API_CONFIG_JSON__;

const readline = require("readline");
const rl = readline.createInterface({ input: process.stdin });

function send(obj) {
  process.stdout.write(JSON.stringify(obj) + "\\n");
}

rl.on("line", function(line) {
  var msg;
  try { msg = JSON.parse(line); } catch (e) { return; }
  if (!msg || msg.jsonrpc !== "2.0") return;
  if (msg.id === undefined || msg.id === null) return;

  var id = msg.id;
  var method = msg.method;
  var params = msg.params || {};

  switch (method) {
    case "initialize":
      send({
        jsonrpc: "2.0",
        id: id,
        result: {
          protocolVersion: "2024-11-05",
          capabilities: { tools: {} },
          serverInfo: { name: CONFIG.toolName, version: "1.0.0" }
        }
      });
      break;

    case "tools/list":
      send({
        jsonrpc: "2.0",
        id: id,
        result: {
          tools: [{
            name: CONFIG.toolName,
            description: CONFIG.toolDescription,
            inputSchema: CONFIG.inputSchema
          }]
        }
      });
      break;

    case "tools/call": {
      var toolName = params.name;
      if (toolName !== CONFIG.toolName) {
        send({ jsonrpc: "2.0", id: id, error: { code: -32601, message: "unknown tool: " + toolName } });
        break;
      }
      var args = params.arguments || {};

      var url = CONFIG.apiUrl;
      var fetchOpts = { method: CONFIG.method, signal: undefined };
      var controller = new AbortController();
      var timer = setTimeout(function() { controller.abort(); }, CONFIG.timeoutMs);
      fetchOpts.signal = controller.signal;

      if (CONFIG.method === "GET") {
        var qs = new URLSearchParams(args).toString();
        if (qs) url += (url.indexOf("?") >= 0 ? "&" : "?") + qs;
      } else if (CONFIG.method === "POST") {
        fetchOpts.headers = { "Content-Type": "application/json" };
        fetchOpts.body = JSON.stringify(args);
      }

      fetch(url, fetchOpts)
        .then(function(r) { return r.text(); })
        .then(function(text) {
          clearTimeout(timer);
          send({
            jsonrpc: "2.0",
            id: id,
            result: { content: [{ type: "text", text: text }] }
          });
        })
        .catch(function(err) {
          clearTimeout(timer);
          send({
            jsonrpc: "2.0",
            id: id,
            error: { code: -32603, message: err.message }
          });
        });
      break;
    }

    default:
      send({ jsonrpc: "2.0", id: id, error: { code: -32601, message: "method not found: " + method } });
  }
});

rl.on("close", function() { process.exit(0); });
`;

const RUN_SH_TEMPLATE = `#!/bin/sh
# AUTO-GENERATED by capability-installer.ts
node "$(dirname "$0")/server.cjs"
`;

// ─── Public API ───────────────────────────────────────────────

export interface InstallResult {
  mcpPackagePath: string;   // absolute path to mcp/<name>/
  resourceId: string;       // same as api.name
}

/**
 * Generate (or regenerate) the stdio-wrapper MCP package for a RegisteredApi.
 * Also updates data/mcp.json so mcp-config.ts picks it up.
 * Idempotent: safe to call multiple times for the same API.
 */
export function installApiAsMcp(api: RegisteredApi): InstallResult {
  if (!VALID_PLUGIN_NAME.test(api.name)) {
    throw new Error(`Invalid API name "${api.name}": must match ${VALID_PLUGIN_NAME}`);
  }

  const pkgDir = path.resolve(MCP_ROOT, api.name);

  // Security: verify pkgDir is within MCP_ROOT (path containment)
  const realPkgDir = path.resolve(pkgDir);
  const realRoot = fs.realpathSync(MCP_ROOT);
  if (!realPkgDir.startsWith(realRoot + path.sep) && realPkgDir !== realRoot) {
    throw new Error(`Path escapes mcp/ directory: ${api.name}`);
  }

  // Create package directory
  fs.mkdirSync(pkgDir, { recursive: true });

  // Build the JSON config object (embedded in wrapper, never string-interpolated JS)
  const config = {
    toolName: api.name,
    toolDescription: api.displayName || api.description || api.name,
    apiUrl: api.apiUrl,
    method: api.method,
    timeoutMs: api.timeoutMs,
    inputSchema: api.requestParamsSchema || { type: "object", properties: {}, required: [] },
  };

  // Generate server.cjs — embed config as JSON, not interpolated JS
  const serverCjs = WRAPPER_TEMPLATE.replace(
    "__API_CONFIG_JSON__",
    JSON.stringify(config, null, 2)
  );
  fs.writeFileSync(path.join(pkgDir, "server.cjs"), serverCjs);

  // Generate run.sh
  const runShPath = path.join(pkgDir, "run.sh");
  fs.writeFileSync(runShPath, RUN_SH_TEMPLATE);
  fs.chmodSync(runShPath, 0o755);

  // Generate mcp.json manifest
  const manifest = {
    name: api.name,
    version: "1.0.0",
    description: api.description || api.displayName || api.name,
  };
  fs.writeFileSync(path.join(pkgDir, "mcp.json"), JSON.stringify(manifest, null, 2) + "\n");

  // Update data/mcp.json (write-temp-and-rename for idempotency)
  upsertMcpConfig(api.name, `mcp/${api.name}`, api.status === "active");

  console.log(`[capability-installer] Installed MCP wrapper for "${api.name}" → ${pkgDir}`);

  return {
    mcpPackagePath: pkgDir,
    resourceId: api.name,
  };
}

/**
 * Remove the MCP package and data/mcp.json entry for an API.
 */
export function uninstallApiMcp(apiName: string): void {
  if (!VALID_PLUGIN_NAME.test(apiName)) {
    throw new Error(`Invalid API name: ${apiName}`);
  }

  const pkgDir = path.resolve(MCP_ROOT, apiName);
  if (fs.existsSync(pkgDir)) {
    fs.rmSync(pkgDir, { recursive: true, force: true });
    console.log(`[capability-installer] Removed MCP package for "${apiName}"`);
  }

  removeMcpConfig(apiName);
}

// ─── data/mcp.json management (write-temp-and-rename) ─────────

interface McpConfigEntry {
  name: string;
  type: "local";
  enabled: boolean;
  path: string;
  description?: string;
}

function loadMcpConfig(): McpConfigEntry[] {
  if (!fs.existsSync(MCP_CONFIG)) return [];
  try {
    return JSON.parse(fs.readFileSync(MCP_CONFIG, "utf8")) as McpConfigEntry[];
  } catch {
    return [];
  }
}

function upsertMcpConfig(name: string, mcpPath: string, enabled: boolean): void {
  const config = loadMcpConfig();
  const existing = config.find((c) => c.name === name);
  if (existing) {
    existing.path = mcpPath;
    existing.enabled = enabled;
  } else {
    config.push({ name, type: "local", enabled, path: mcpPath });
  }
  writeMcpConfig(config);
}

function removeMcpConfig(name: string): void {
  const config = loadMcpConfig().filter((c) => c.name !== name);
  writeMcpConfig(config);
}

function writeMcpConfig(config: McpConfigEntry[]): void {
  const content = JSON.stringify(config, null, 2) + "\n";
  const tmpPath = MCP_CONFIG + ".tmp";
  fs.mkdirSync(path.dirname(MCP_CONFIG), { recursive: true });
  fs.writeFileSync(tmpPath, content);
  fs.renameSync(tmpPath, MCP_CONFIG);
}

